import type { Illustration } from '../core/illustration';
import type { SayKind } from '../state/store';

export interface ScriptLine {
  text: string;
  kind: SayKind;
  cite?: string;
  quote?: string;
  /** Words to highlight in the segment while this line is said. */
  words?: string;
}

export interface GlossEntry {
  /** Plain letters, as the word appears in the text. */
  word: string;
  meaning: string;
  lang: 'ארמית' | 'עברית' | 'מונח';
  /** A commentary line that explains the word, if there is one. */
  cite?: string;
  quote?: string;
}

export interface DemoSection {
  /** Segment number → lines to say when learning it. */
  segments: Record<number, ScriptLine[]>;
  glossary: GlossEntry[];
  illustrations: Partial<Record<'default' | 'compare' | 'change', Illustration>>;
  /** Facts the demo can check a learner's claim against. */
  claims: { who: RegExp; whoHe: string; holds: string; key: RegExp; cite: string; quote: string }[];
  summary: { learned: string[]; terms: string[]; review: string[] };
  /** Answers for common questions on this section. */
  answers: { match: RegExp; lines: ScriptLine[] }[];
}

