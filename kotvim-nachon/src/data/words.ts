export interface WordEntry {
  w: string;
  n?: string;
  e?: string;
  g: number;
  x: string[];
}

function parse(raw: string): WordEntry[] {
  return raw
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((line) => {
      const [w, n, e, g, x] = line.split('|');
      return {
        w: w.trim(),
        n: n?.trim() || undefined,
        e: e?.trim() || undefined,
        g: Number(g) || 1,
        x: x ? x.split(',').map((s) => s.trim()).filter(Boolean) : [],
      };
    })
    .filter((e) => e.g <= 8);
}

export const WORDS: Record<SkillId, WordEntry[]> = Object.fromEntries(
  Object.entries(RAW).map(([k, v]) => [k, v.trim() ? parse(v) : []]),
) as Record<SkillId, WordEntry[]>;

/** Every correctly spelled word we know – used as a small lexicon by the offline checker. */
export function allKnownWords(): Set<string> {
  const s = new Set<string>();
  for (const list of Object.values(WORDS)) for (const e of list) s.add(e.w);
  return s;
}

/** Look up nikud for a word if we have it (for TTS and reading support). */
export function nikudFor(word: string): string | undefined {
  for (const list of Object.values(WORDS)) {
    const hit = list.find((e) => e.w === word && e.n);
    if (hit) return hit.n;
  }
  return undefined;
}
