/** Grade band: 1 = grades 1-2, 2 = grades 3-4, 3 = grades 5 and up. */
export function bandFor(grade: number): 1 | 2 | 3 {
  if (grade <= 2) return 1;
  if (grade <= 4) return 2;
  return 3;
}

